/** 扁平词表：[{ term, domain, ascii }]，按归一化后的词去重。 */
export const DOMAIN_TERMS = (() => {
  const seen = new Set();
  const out = [];
  for (const [domain, terms] of Object.entries(GROUPS)) {
    for (const raw of terms) {
      const term = String(raw).trim();
      const key = term.toLowerCase();
      if (!term || seen.has(key)) continue;
      seen.add(key);
      out.push({ term, domain, ascii: ASCII_RE.test(term) });
    }
  }
  return out;
})();

export const DOMAIN_TERM_COUNT = DOMAIN_TERMS.length;
export const DOMAIN_GROUPS = Object.keys(GROUPS);

const ASCII_TERMS = DOMAIN_TERMS.filter((entry) => entry.ascii);
const CJK_TERMS = DOMAIN_TERMS.filter((entry) => !entry.ascii);

function escapeRe(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// 英文词合并成一个交替正则一次扫完（30+ 个单独 test 太浪费）
const ASCII_RE_ALL = ASCII_TERMS.length
  ? new RegExp(`(?:^|[^a-z0-9])(?:${ASCII_TERMS.map((entry) => escapeRe(entry.term.toLowerCase())).join('|')})(?![a-z0-9])`, 'i')
  : null;

/**
 * 抽取文本命中的专业词。
 * @returns {{ terms: {term:string, domain:string}[], domains: string[], score: number }}
 * score 只是「命中密度」的粗略提示：命中的专业词越多，越值得联网核实。
 */
export function extractDomainTerms(text, { extraTerms = [] } = {}) {
  const source = String(text ?? '');
  if (!source) return { terms: [], domains: [], score: 0 };
  const lower = source.toLowerCase();
  const hits = [];
  const seen = new Set();

  for (const entry of CJK_TERMS) {
    if (seen.has(entry.term)) continue;
    if (source.includes(entry.term)) {
      seen.add(entry.term);
      hits.push({ term: entry.term, domain: entry.domain });
    }
  }
  if (ASCII_RE_ALL) {
    for (const entry of ASCII_TERMS) {
      if (seen.has(entry.term)) continue;
      // 单个交替正则只能告诉我「至少有一个」，要具体是哪个还得逐词判；
      // 但 30 个词的正则很便宜，先用大正则做一次否决，命中再逐词定位。
      if (!ASCII_RE_ALL.test(lower)) break;
      const re = new RegExp(`(?:^|[^a-z0-9])${escapeRe(entry.term.toLowerCase())}(?![a-z0-9])`, 'i');
      if (re.test(lower)) {
        seen.add(entry.term);
        hits.push({ term: entry.term, domain: entry.domain });
      }
    }
  }
  for (const raw of extraTerms) {
    const term = String(raw ?? '').trim();
    if (!term || seen.has(term)) continue;
    if (source.toLowerCase().includes(term.toLowerCase())) {
      seen.add(term);
      hits.push({ term, domain: '自定义' });
    }
  }

  const domains = [...new Set(hits.map((hit) => hit.domain))];
  return { terms: hits, domains, score: hits.length };
}
